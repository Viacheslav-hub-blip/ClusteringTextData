"""Конфигурация prompt-запросов для pipeline кластеризации.

Файл содержит:
- ``PrimaryPromptConfig`` — prompt-настройки упрощенной кластеризации.
"""

from __future__ import annotations

from dataclasses import dataclass

DOMAIN_CONTEXT = """
Ты работаешь с пользовательскими текстовыми комментариями. Нужно группировать записи по
смыслу проблемы, а не по совпадению отдельных слов. Важные детали комментария:
конкретная операция, продукт, сервис, канал, место, получатель платежа, повторяемость действия
и фактическое препятствие, с которым столкнулся клиент.
""".strip()

CLUSTERING_POLICY_BLOCK = """
Правила кластеризации:
1. Сначала выдели ядро кейса: что пользователь пытался сделать, где или с чем он это делал,
   что именно помешало и какой результат стал невозможен.
2. Объединяй комментарии только если совпадают действие, объект жалобы, причина недовольства
   и ожидаемое изменение. Общая тема "операция заблокирована", "нужно подтверждение",
   "платеж не прошел" сама по себе недостаточна.
3. Не объединяй кейсы с разными значимыми сущностями, если именно они объясняют проблему:
   офис, банкомат, приложение, СМС, автоплатеж, подписка, конкретный сервис или получатель
   платежа вроде Wink, МТС, MOVAVI.
4. Не объединяй противоположные смыслы, даже если они используют одинаковые слова.
5. Не добавляй общий негатив без конкретного кейса в содержательные группы.
6. Не выдумывай факты, которых нет в исходном тексте.
7. При сомнении выбирай более узкую группу или новую группу.

Примеры границ групп:
- "операцию заблокировали в офисе, разблокировка заняла месяц" — отдельный кейс
  "Блокировка операции в офисе", а не общая группа про длительную блокировку операций.
- "списание 11 рублей от кинотеатра Wink приостановлено" — отдельный кейс
  "Проблемы оплаты Wink", а не общая группа про блокировку операций.
- "после остановки автоплатеж нельзя повторить" — отдельный кейс
  "Невозможно повторить автоплатеж", а не общая группа про уровень безопасности.
""".strip()

PRIMARY_DECISION_SYSTEM = f"""
Ты выбираешь, относится ли новый комментарий к одной из существующих групп или требует новой группы.

{DOMAIN_CONTEXT}

{CLUSTERING_POLICY_BLOCK}

Перед выбором existing_group обязательно сравни новый комментарий с названием и примерами
кандидатной группы по четырем признакам:
1. действие или операция клиента;
2. объект или сервис, с которым связана проблема;
3. канал, место или контекст выполнения;
4. фактическое препятствие.

Если совпадает только общий банковский процесс, но отличается сервис, место, канал или действие,
выбирай new_group. Узкая новая группа лучше широкой группы, в которой потом нельзя понять
смысл отдельных элементов.

Верни только валидный JSON без markdown.
JSON должен содержать поля:
- decision_type: existing_group или new_group;
- group_id: ID выбранной группы или пустая строка для новой группы;
- reason: краткое объяснение выбора.
""".strip()

PRIMARY_DECISION_HUMAN = """
Исходный комментарий:
{raw_text}

Нормализованный комментарий:
{normalized_text}

Кандидатные группы:
{candidate_groups}
""".strip()

GROUP_NAMING_SYSTEM = f"""
Ты генерируешь короткое название группы пользовательских комментариев.

{DOMAIN_CONTEXT}

Название должно объяснять общий смысл элементов группы так, чтобы по нему было понятно,
почему эти комментарии лежат вместе.

Правила названия:
1. Используй 3-7 слов, без точки в конце.
2. Сохраняй важную сущность из комментариев: сервис, место, канал, продукт, тип операции
   или действие клиента.
3. Формулируй название как конкретный кейс, а не как широкую тему.
4. Не используй слишком общие слова без уточнения: "проблемы с операциями",
   "длительная блокировка операций", "несоответствие ожиданиям", "сложный процесс".
5. Не добавляй деталей, которых нет в примерах.
6. Если группа состоит из одного комментария, называй ее по главному факту этого комментария.

Ориентиры качества:
- "Блокировка операции в офисе" лучше, чем "Длительная блокировка операций и сложный процесс разблокировки".
- "Проблемы оплаты Wink" лучше, чем "Длительная блокировка операций".
- "Невозможно повторить автоплатеж" лучше, чем "Несоответствие уровня безопасности ожиданиям клиента".
- "Задержка СМС-подтверждения" лучше, чем "Длительное ожидание выполнения операции".

Верни только валидный JSON без markdown.
JSON должен содержать поле:
- group_name: короткое человекочитаемое название группы.
""".strip()

GROUP_NAMING_HUMAN = """
Примеры комментариев группы:
{group_examples}
""".strip()


@dataclass(slots=True)
class PrimaryPromptConfig:
    """Prompt-конфигурация базового pipeline.

    Args:
        primary_decision_system: System prompt для выбора существующей или новой группы.
        primary_decision_human: Human prompt для выбора существующей или новой группы.
        group_naming_system: System prompt для генерации имени группы.
        group_naming_human: Human prompt для генерации имени группы.

    Returns:
        Экземпляр с шаблонами prompt-ов, которые используются при сборке LCEL-цепочек.
    """

    primary_decision_system: str
    primary_decision_human: str
    group_naming_system: str
    group_naming_human: str

    @classmethod
    def default(cls) -> "PrimaryPromptConfig":
        """Создает конфигурацию базовых prompt-ов из дефолтов библиотеки.

        Returns:
            Конфигурация с дефолтными prompt-шаблонами библиотеки.
        """
        return cls(
            primary_decision_system=PRIMARY_DECISION_SYSTEM,
            primary_decision_human=PRIMARY_DECISION_HUMAN,
            group_naming_system=GROUP_NAMING_SYSTEM,
            group_naming_human=GROUP_NAMING_HUMAN,
        )
