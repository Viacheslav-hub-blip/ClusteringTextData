CLUSTERING_POLICY_BLOCK = """
Общие правила кластеризации:

1. Группа должна объединять комментарии прежде всего по продукту, услуге или клиентскому сценарию операции.

Главная ось кластеризации:
- продукт или услуга: мобильная связь, интернет, доставка еды, маркетплейс, подписка, кредит, вклад, карта;
- тип операции: оплата, перевод, СБП, снятие наличных, пополнение, списание, возврат, подтверждение;
- получатель или категория получателя: МТС, Мегафон, оператор связи, интернет-провайдер, сервис доставки еды, банкомат, магазин.

Если продукт или услуга явно не указаны, используй следующую доступную ось: тип операции, канал или тип проблемы.
Например, "долго подтверждается операция" можно отнести к группе про долгое подтверждение, если из текста не видно,
что это оплата телефона, интернета, доставки еды или другой конкретной услуги.

Комментарий можно отнести к существующей группе, если совпадает основной продукт/услуга или сценарий операции,
даже если отличается формулировка проблемы: блокировка, подтверждение, задержка, комиссия, отказ, неудобство.

Второстепенные детали не должны автоматически создавать новую группу, если совпадает продуктовая категория
и клиентский сценарий. К второстепенным деталям относятся отдельная сумма, конкретная эмоция, порядок слов,
единичный канал обращения или несущественная детализация.

2. Не объединяй комментарии только из-за совпадения общих слов:
"подтверждение", "блокировка", "операция", "перевод", "деньги", "безопасность",
"негативный комментарий".

Эти слова являются слишком общими и сами по себе не доказывают общий смысл.

3. Разделяй противоположные смыслы.

Например, это разные группы:
- банк не остановил мошенников / недостаточная защита;
- банк слишком часто блокирует клиента / избыточная защита.

4. Не разделяй один и тот же продуктовый сценарий только по типу проблемы, если пользователь ожидает анализ по продуктам и услугам.

Например, комментарии про оплату мобильной связи можно объединять в одну группу:
- не проходит оплата МТС;
- заблокировали оплату Мегафона;
- долго подтверждается платеж за мобильную связь;
- не приходит код при оплате телефона.

Это одна продуктовая зона: проблемы с оплатой мобильной связи. Тип проблемы можно отражать в примерах или дополнительном описании,
но не обязательно создавать отдельную группу под каждый вариант.

5. Разделяй проблемы операции и проблемы коммуникации.

Например:
- "остановка происходит там, где это не нужно" — проблема остановки операции;
- "устал от ваших сообщений" — проблема избыточных сообщений.

Их нельзя объединять только потому, что оба комментария негативные.

6. Разделяй техническую проблему и антифрод-блокировку.

Например:
- "не смог снять деньги с банкомата" — техническая или банкоматная проблема;
- "банк блокирует снятие наличных" — блокировка доступа к средствам.

7. Сохраняй конкретные сущности и используй их для выбора продуктовой группы:
- компании;
- бренды;
- продукты;
- сервисы;
- типы операций;
- суммы;
- каналы;
- получателей;
- места совершения операции;
- банк/приложение/банкомат/терминал/оператор/900/офис.

Если конкретные сущности относятся к одной категории услуг, объединяй их на уровне категории.
Например, МТС и Мегафон относятся к мобильной связи; разные сервисы доставки еды относятся к доставке еды;
разные интернет-провайдеры относятся к оплате интернета.

8. Если комментарии похожи по проблеме, но относятся к разным продуктовым сценариям, их нужно разделять.

Например:
- проблема с оплатой мобильной связи;
- проблема с оплатой интернета;
- проблема с оплатой доставки еды;
- проблема со снятием наличных;
- проблема с переводом через СБП;
- проблема с подписками и регулярными списаниями;
- проблема с банкоматом или терминалом.

9. Если комментарий содержит только общую эмоцию без фактов, он не должен попадать в содержательную группу.

Например:
- "ужас";
- "всё может быть лучше";
- ".";
- случайные символы.

Такие комментарии относятся к группе:
"Общие негативные оценки без конкретной причины" или "Неинформативные комментарии".

10. Позитивные комментарии, благодарности, похвалы, сообщения об удобстве, скорости или отсутствии проблем можно объединять в одну общую позитивную группу, если в них нет отдельного конкретного предложения или жалобы.

11. Не выдумывай факты, которых нет в тексте.

12. Для негативных комментариев конкретные сущности и детали нужно сохранять максимально точно.

13. Не пытайся искусственно уменьшить количество групп за счет объединения разных продуктовых сценариев,
но и не создавай новую группу только из-за частных деталей внутри той же услуги или операции.

Лучше выбрать существующую группу, если комментарий относится к той же услуге, продукту или операции,
даже если тип сбоя или детали кейса отличаются.
""".strip()

